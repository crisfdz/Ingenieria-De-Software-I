let a = 10;
console.log(a > 5);
console.log(a >= 10);
console.log(a < 5);
console.log(a <= 5);

console.log(a == 10); // pregunta por el valor
console.log(a != 10);
console.log(a === 10); // también compara el tipo
console.log(a === "10");
console.log(a !== 10); // distinto tipo de dato y valor
console.log(a !== "10");
